#!/usr/bin/env node
/**
 * Reads every course's keyword list (out/keywords/*.json) and shows how the
 * courses relate: how many keywords each has, which are already covered by a
 * post, and which keywords are shared between courses (those should become one
 * post that links to every course, not one near-duplicate post per course).
 *
 *   node scripts/seo/keyword-clusters.mjs
 *
 * Writes docs/seo/keyword-clusters.md (committed).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..', '..');
const KW = path.join(HERE, 'out', 'keywords');
const COURSES = JSON.parse(fs.readFileSync(path.join(HERE, 'data', 'courses.json'), 'utf8')).courses;

// Noise that is never worth a page, whatever the course.
const NOISE = /\bpdf\b.*\bdownload\b|near me|\bhindi\b|\burdu\b|\btamil\b|\btelugu\b|\bkannada\b|\bmarathi\b|\bbengali\b|\bspanish\b|\bfrench\b|\btagalog\b|\bmalay\b|\bnepali\b|\bkids?\b|\bchildren\b|\bclass \d|\bcbse\b|\bncert\b|\bquiz(let)?\b|\bin (noida|delhi|mumbai|pune|bangalore|bengaluru|hyderabad|chennai|kolkata|ameerpet|gurgaon|jaipur|lahore|karachi|dhaka|bangladesh|nepal|kerala|lucknow|ahmedabad|chandigarh|kochi|indore|bhopal|coimbatore|vizag)\b|\bameerpet\b|\bfees\b|\bmeme\b|\bsong\b|\blyrics\b/;

const byCourse = new Map();
for (const c of COURSES) {
  const f = path.join(KW, `${c.slug}.json`);
  if (!fs.existsSync(f)) continue;
  byCourse.set(c.slug, { course: c, rows: JSON.parse(fs.readFileSync(f, 'utf8')).filter((r) => !NOISE.test(r.keyword)) });
}

// keyword -> courses that surfaced it
const owners = new Map();
for (const [slug, { rows }] of byCourse) {
  for (const r of rows) {
    if (!owners.has(r.keyword)) owners.set(r.keyword, []);
    owners.get(r.keyword).push({ slug, score: r.score });
  }
}

const lines = ['# Keyword clusters across all courses', '',
  'Generated by `scripts/seo/keyword-clusters.mjs` from the autocomplete lists. Noise (other languages, kids, quizzes, "near me") is removed first.', ''];

// Overview table
lines.push('## Overview', '', '| Category | Course | Keywords | Already covered | Shared with another course |', '| --- | --- | ---: | ---: | ---: |');
for (const { course, rows } of byCourse.values()) {
  const shared = rows.filter((r) => owners.get(r.keyword).length > 1).length;
  lines.push(`| ${course.category} | ${course.title} | ${rows.length} | ${rows.filter((r) => r.coveredBy).length} | ${shared} |`);
}
lines.push('');

// Overlap pairs
const pair = new Map();
for (const list of owners.values()) {
  if (list.length < 2) continue;
  for (let i = 0; i < list.length; i++) for (let j = i + 1; j < list.length; j++) {
    const k = [list[i].slug, list[j].slug].sort().join(' + ');
    pair.set(k, (pair.get(k) ?? 0) + 1);
  }
}
const pairs = [...pair.entries()].sort((a, b) => b[1] - a[1]).filter(([, n]) => n >= 15).slice(0, 25);
lines.push('## Courses that compete for the same searches', '', 'One shared post per pair, linking to both courses, beats two near-duplicates.', '',
  '| Courses | Shared keywords |', '| --- | ---: |', ...pairs.map(([k, n]) => `| ${k} | ${n} |`), '');

// Per category detail
const cats = [...new Set(COURSES.map((c) => c.category))];
for (const cat of cats) {
  lines.push(`## ${cat}`, '');
  for (const { course, rows } of [...byCourse.values()].filter((v) => v.course.category === cat)) {
    const fresh = rows.filter((r) => !r.coveredBy && owners.get(r.keyword).length === 1).slice(0, 14);
    lines.push(`### ${course.title}`, '',
      `Top keywords only this course has: ${fresh.map((r) => `${r.keyword} (${r.score})`).join('; ') || 'none'}`, '');
  }
}

const out = path.join(REPO, 'docs', 'seo', 'keyword-clusters.md');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
console.log(`${byCourse.size} courses → ${path.relative(REPO, out)}`);
